import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
import {repairVideoDisplay} from './finalize-video-edition.mjs';
import {videoPublishedToday} from './run-scheduled-update.mjs';
const {finalizeExpertVideoEdition,selectDailyExpertVideoArchivePicks,shouldRefreshExpertVideos}=createRequire(import.meta.url)('./expert-video.cjs');
const now=Date.parse('2026-09-19T00:00:00Z');
const v=(id,person,extra={})=>({content_type:'expert_video',video_id:id,expert_id:person,
  title:'AIの仕組みを学ぶ',source_date_status:'published',source_published_at:'2026-09-18T03:00:00Z',...extra});
const before={status:'published',last_published_day_jst:'2026-09-18',last_published_at:'2026-09-18T04:00:00Z',
  featured_video_keys:['a','b'],featured_expert_ids:['a','b'],
  published_history:[{day_jst:'2026-09-18',video_key:'a',expert_id:'a'},{day_jst:'2026-09-18',video_key:'b',expert_id:'b'}]};
const previous=[v('a','a',{home_video_selected_at:before.last_published_at}),v('b','b',{home_video_selected_at:before.last_published_at})];
const stale=finalizeExpertVideoEdition(previous,before,now,{refreshDue:true});
assert.equal(stale.state.featured_video_keys.length,2,'zero new candidates does not erase the prior pair');
assert.equal(stale.state.continued_count,2);
assert.equal(stale.state.last_published_at,before.last_published_at,'no fake refresh time');
assert.equal(videoPublishedToday(stale.state,stale.items,now),false);
assert.ok(shouldRefreshExpertVideos(stale.state,now));
const one=repairVideoDisplay([...previous,v('c','c')],before,now);
assert.equal(one.state.featured_video_keys.length,2);
assert.equal(one.state.fresh_selected_count,1);
assert.equal(one.state.continued_count,1);
assert.equal(one.state.status,'partial');
const again=repairVideoDisplay(one.items,one.state,now+60000);
assert.deepEqual(again.state.featured_video_keys,one.state.featured_video_keys,'carryover and new pick stay stable during retries');
assert.equal(again.state.fresh_selected_count,1);
assert.equal(again.state.published_history.length,one.state.published_history.length);
const complete=repairVideoDisplay([...again.items,v('d','d')],again.state,now+120000);
assert.deepEqual(new Set(complete.state.featured_video_keys),new Set(['c','d']));
assert.equal(videoPublishedToday(complete.state,complete.items,now+120000),true);
assert.equal(complete.state.continued_count,0);
assert.equal(complete.items.find(x=>x.video_id==='a').home_video_selected_at,'');
assert.equal(complete.items.find(x=>x.video_id==='a').source_published_at,previous[0].source_published_at);
const reserve=repairVideoDisplay([...previous,v('c','c'),v('older','z')],before,now);
assert.deepEqual(new Set(reserve.state.featured_expert_ids),new Set(['c','z']),'prefer a different creator before any previous-day carryover');
const cap=selectDailyExpertVideoArchivePicks([...previous,v('c','c')],before,2,now);
assert.equal(cap.length,2);
assert.ok(cap.some(x=>x.video_id==='c'));
assert.ok(cap.some(x=>x.video_id==='a'||x.video_id==='b'),'archive cap reserves an actual display pair');
const joint=repairVideoDisplay([...previous,v('joint','c',{expert_ids:['c','a','b']})],before,now);
assert.deepEqual(new Set(joint.state.featured_video_keys),new Set(['a','b']),'do not let a blocking joint appearance reduce a valid pair to one');
assert.equal(videoPublishedToday(joint.state,joint.items,now),false);
assert.equal(joint.state.last_published_at,before.last_published_at);
assert.ok(!joint.state.published_history.some(x=>x.video_key==='joint'),'a rejected joint pick was never published');
assert.throws(()=>repairVideoDisplay([v('only','a')],before,now),/publication held/,'never publish a one-card replacement');
assert.throws(()=>repairVideoDisplay([v('a','a'),v('a2','a')],before,now),/publication held/);
assert.throws(()=>repairVideoDisplay([v('a','a'),v('old','b',{source_published_at:'2026-09-01T00:00:00Z'})],before,now),/publication held/,'ten-day limit is not silently relaxed');
const news={content_type:'article',article_id:'news',home_top_rank:1,detail:'untouched'};
assert.equal(repairVideoDisplay([news,...previous],before,now).items[0],news);
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8').replace(/\r\n?/g,'\n');
const selector=html.match(/function homeExpertVideos\(items\)\{[\s\S]*?\n\}/)[0];
const browserSelect=Function('isExpertVideo','byFeedOrder',selector+';return homeExpertVideos;')(x=>x.content_type==='expert_video',(a,b)=>Date.parse(b.source_published_at)-Date.parse(a.source_published_at));
const recent=new Date(Date.now()-86400000).toISOString();
const selected=v('active','c',{source_published_at:recent,home_video_selected_at:recent});
const backup=v('backup','a',{source_published_at:recent,home_video_reserve:true});
assert.equal(browserSelect([selected,backup]).length,2,'browser fills a missing/expired card only with explicitly reviewed reserve');
assert.equal(browserSelect([selected,backup])[1].home_video_origin,'continued');
assert.equal(browserSelect([{...selected,expert_ids:['c','a','b']},backup,{...backup,video_id:'backup-b',expert_id:'b'}]).length,2,'browser also avoids a blocking co-presenter');
assert.equal(browserSelect([selected,{...backup,home_video_reserve:false}]).length,1,'old unapproved cache is not a reserve');
assert.ok(html.includes('本日の新着')&&html.includes('継続掲載'));
const workflow=fs.readFileSync(new URL('../.github/workflows/update.yml',import.meta.url),'utf8');
assert.ok(workflow.indexOf('node scripts/finalize-video-edition.mjs')>workflow.indexOf('- name: validate published articles'));
assert.ok(workflow.indexOf('node scripts/finalize-video-edition.mjs')<workflow.indexOf('- name: persist validated public data'));
console.log('Two-video availability passed: zero/one new, carryover, retries, completed replacement, diversity, cap, expiry, post-validation gate and browser reserve.');
