import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
import {videoPublishedToday} from './run-scheduled-update.mjs';
const {finalizeExpertVideoEdition,shouldRefreshExpertVideos,selectDailyExpertVideoArchivePicks,isSubstantiveAiVideo}=createRequire(import.meta.url)('./expert-video.cjs');
const now=Date.parse('2026-09-16T00:00:00Z');
const video=(id,person,extra={})=>({content_type:'expert_video',video_id:id,expert_id:person,
  title:'AIの仕組みを解説',source_date_status:'published',source_published_at:'2026-09-15T10:00:00Z',...extra});
const items=[video('a1','a'),video('a2','a'),video('b1','b'),video('c1','c',{expert_tier:'practical_ai_educator'})];
const state={published_history:[{day_jst:'2026-09-15',video_key:'a0',expert_id:'a'}],featured_video_key:'a0',last_published_day_jst:'2026-09-15'};
const first=finalizeExpertVideoEdition(items,state,now,{refreshDue:true});
assert.deepEqual(first.state.featured_video_keys,['c1','b1'],'learning plus less recently featured voice beats repeated daily uploader');
assert.equal(videoPublishedToday(first.state,first.items,now),true);
assert.equal(shouldRefreshExpertVideos(first.state,now),false);
const stable=finalizeExpertVideoEdition([...items,video('d1','d')],first.state,now+3600000,{refreshDue:true});
assert.deepEqual(stable.state.featured_video_keys,first.state.featured_video_keys,'two completed picks stay stable all day');
assert.equal(stable.state.published_history.length,first.state.published_history.length,'retry does not duplicate history');
const partial=finalizeExpertVideoEdition(items.slice(0,2),state,now,{refreshDue:true});
assert.equal(partial.state.featured_video_keys.length,1,'never fill both slots with the same creator');
assert.equal(partial.state.status,'partial');
assert.equal(videoPublishedToday(partial.state,partial.items,now),false);
assert.equal(shouldRefreshExpertVideos(partial.state,now),true,'second slot can recover at next retry');
const filled=finalizeExpertVideoEdition([...partial.items,items[2]],partial.state,now+60000,{refreshDue:true});
assert.equal(videoPublishedToday(filled.state,filled.items,now+60000),true);
assert.ok(filled.state.featured_video_keys.includes(partial.state.featured_video_key),'retry preserves first new pick');
const carried=video('carry','z',{home_video_selected_at:'2026-09-15T00:00:00Z'});
const partialWithCarry={...partial.state,featured_video_keys:[partial.state.featured_video_key,'carry'],published_history:[...partial.state.published_history,{video_key:'carry',expert_id:'z',day_jst:'2026-09-15'}]};
const retryCap=selectDailyExpertVideoArchivePicks([...partial.items,carried,items[2]],partialWithCarry,2,now);
assert.ok(retryCap.some(x=>x.video_id==='b1'),'carried old video must not crowd out the second fresh pick during retry');
const cap=selectDailyExpertVideoArchivePicks(items,state,2,now);
assert.deepEqual(cap.map(x=>x.video_id),first.state.featured_video_keys,'archive cap protects both intended picks');
const tomorrow=finalizeExpertVideoEdition([...first.items,video('a3','a'),video('d1','d')],first.state,now+86400000,{refreshDue:true});
assert.ok(tomorrow.state.featured_video_keys.every(id=>!first.state.featured_video_keys.includes(id)),'next day never relabels previous videos as fresh');
const expired=finalizeExpertVideoEdition([video('old','x',{source_published_at:'2026-09-01T00:00:00Z'})],{},now,{refreshDue:true});
assert.equal(expired.state.featured_video_keys.length,0);
const duplicateTopic=finalizeExpertVideoEdition([video('x','a',{story_subject:'same'}),video('y','b',{story_subject:'same'})],{},now,{refreshDue:true});
assert.equal(duplicateTopic.state.featured_video_keys.length,1,'do not fill two slots with the same topic');
assert.equal(isSubstantiveAiVideo('生成AIの使い方・プロンプトのコツ'),true);
assert.equal(isSubstantiveAiVideo('AI講座の受講者募集'),false);
const registry=JSON.parse(fs.readFileSync(new URL('../expert-sources.json',import.meta.url)));
assert.ok(registry.experts.filter(x=>x.tier==='practical_ai_educator'&&x.official_sources.length).length>=2);
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
assert.ok(html.includes('LEARN AI')&&html.includes('AIを学ぶ動画'));
assert.ok(html.includes('grid-template-columns:repeat(2,minmax(0,1fr))'));
assert.ok(html.includes('@media(max-width:600px){.expert-video-grid{grid-template-columns:1fr}'));
assert.ok(html.includes('-webkit-line-clamp:2}.expert-video-actions'));
console.log('Learning video edition passed: 2 different voices, learning coverage, rotation, partial recovery and compact responsive cards.');
