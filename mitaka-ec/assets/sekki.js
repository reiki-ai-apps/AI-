export function currentSekki(date = new Date()) {
  const m = date.getMonth() + 1, d = date.getDate();
  let cur = TERMS[TERMS.length - 1];
  for (const t of TERMS) { if (m > t[0] || (m === t[0] && d >= t[1])) cur = t; }
  return { name: cur[2], task: cur[3], month: cur[0], day: cur[1] };
}
export const SEKKI = TERMS.map(t => ({ month: t[0], day: t[1], name: t[2], task: t[3] }));
